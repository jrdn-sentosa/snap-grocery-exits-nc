"""Profile qa_batch_end using end dates through 2021-12-31 only (train + validation period).

Reads : data/interim/retailers_nc_clean.parquet
Writes: docs/batch_end_profile.md
        docs/batch_end_handcheck.csv  (written once, never overwritten)

Test-set discipline: every table is built from end dates <= DATA_THROUGH. The successor
check (section 3) is further limited to end dates <= DATA_THROUGH - 90 days, and only
successor rows authorized by DATA_THROUGH are eligible, so its +90-day window never looks
into 2022+. This does not change the qa_batch_end definition (02_clean.py owns that).
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "prep"))
from common import DATA_THROUGH, DOCS, INTERIM, ensure_dirs  # noqa: E402

CUTOFF = pd.Timestamp(DATA_THROUGH)
SUCCESSOR_CUTOFF = CUTOFF - pd.Timedelta(days=90)


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def pct(num: float, den: float) -> str:
    return f"{100 * num / den:.1f}%" if den else "n/a"


def type_group(row_type: pd.Series, is_grocery: pd.Series) -> pd.Series:
    g = pd.Series("Other", index=row_type.index)
    g[row_type == "Convenience Store"] = "Convenience"
    g[row_type == "Combination Grocery/Other"] = "Combination grocery/other"
    g[is_grocery] = "Grocery (5 types)"
    return g


def has_successor(ends: pd.DataFrame, pool: pd.DataFrame, lo: int, hi: int) -> pd.Series:
    """True if a DIFFERENT Record ID at the same address_key was authorized in
    [end + lo days, end + hi days]. Ends without an address_key are False (reported separately)."""
    pool = pool[["record_id", "address_key", "auth_date"]].dropna()
    m = ends[["period_id", "record_id", "address_key", "end_date"]].dropna(subset=["address_key"]).merge(
        pool, on="address_key", suffixes=("", "_succ")
    )
    m = m[m["record_id"] != m["record_id_succ"]]
    delta = (m["auth_date"] - m["end_date"]).dt.days
    hit = set(m.loc[delta.between(lo, hi), "period_id"])
    return ends["period_id"].isin(hit)


def main() -> None:
    ensure_dirs()
    d = pd.read_parquet(INTERIM / "retailers_nc_clean.parquet")
    d["period_id"] = range(len(d))
    d["group"] = type_group(d["store_type"], d["is_grocery"])

    ends = d[d["end_date"].notna() & (d["end_date"] <= CUTOFF)].copy()
    assert ends["end_date"].max() <= CUTOFF
    threshold = int(ends.groupby("end_date").size().loc[lambda s: s.index.isin(ends.loc[ends["qa_batch_end"], "end_date"])].min())
    out = [
        "# qa_batch_end profile (end dates through 2021-12-31 only)",
        "",
        "Generated by `src/eda/batch_end_profile.py`; do not edit by hand. The label definition is",
        "unchanged. All counts are NC SNAP authorization periods that ended on or before",
        f"{DATA_THROUGH}; no 2022+ end dates are used. `qa_batch_end` = the end date is shared by",
        f">= {threshold} NC retailers (all store types) on one day.",
        "",
        f"Ended periods in scope: **{len(ends):,}**; flagged `qa_batch_end`: **{int(ends['qa_batch_end'].sum()):,}** "
        f"({pct(ends['qa_batch_end'].sum(), len(ends))}) on **{ends.loc[ends['qa_batch_end'], 'end_date'].nunique()}** batch dates.",
        "",
    ]

    # (1) batch dates with store-type mix
    b = ends[ends["qa_batch_end"]]
    mix = b.pivot_table(index="end_date", columns="group", values="period_id", aggfunc="count", fill_value=0)
    for g in ("Grocery (5 types)", "Convenience", "Combination grocery/other", "Other"):
        if g not in mix:
            mix[g] = 0
    mix = mix[["Grocery (5 types)", "Convenience", "Combination grocery/other", "Other"]]
    mix.insert(0, "Total", mix.sum(axis=1))
    mix["Grocery share"] = [pct(g, t) for g, t in zip(mix["Grocery (5 types)"], mix["Total"])]
    mix["Convenience share"] = [pct(c, t) for c, t in zip(mix["Convenience"], mix["Total"])]
    mix = mix.sort_index().reset_index()
    mix["end_date"] = mix["end_date"].dt.strftime("%Y-%m-%d")
    mix["weekday"] = pd.to_datetime(mix["end_date"]).dt.day_name().str[:3]
    out += ["## 1. Batch dates and store-type mix", "", md_table(mix), ""]
    tot = mix[["Total", "Grocery (5 types)", "Convenience", "Combination grocery/other", "Other"]].sum()
    out += [
        f"Across all batch dates: {int(tot['Total']):,} ends = {int(tot['Grocery (5 types)']):,} grocery "
        f"({pct(tot['Grocery (5 types)'], tot['Total'])}), {int(tot['Convenience']):,} convenience "
        f"({pct(tot['Convenience'], tot['Total'])}), {int(tot['Combination grocery/other']):,} combination grocery/other "
        f"({pct(tot['Combination grocery/other'], tot['Total'])}), {int(tot['Other']):,} other.",
        "",
    ]

    # (2) share of ends that are batch ends, by type group and grocery subtype
    def share_table(by: str) -> pd.DataFrame:
        g = ends.groupby(by).agg(ended=("period_id", "size"), batch=("qa_batch_end", "sum")).reset_index()
        g["batch_share"] = [pct(x, y) for x, y in zip(g["batch"], g["ended"])]
        g["non_batch"] = g["ended"] - g["batch"]
        return g.sort_values("ended", ascending=False)

    gs = share_table("group")
    sub = share_table("store_type")
    sub = sub[sub["store_type"].isin(d.loc[d["is_grocery"], "store_type"].unique())]
    out += ["## 2. Share of ended periods that are batch ends, by type", "", md_table(gs), "",
            "Grocery subtypes:", "", md_table(sub), ""]

    # (3) successor at the same address
    e3 = ends[ends["end_date"] <= SUCCESSOR_CUTOFF].copy()
    pool = d[d["auth_date"].notna() & (d["auth_date"] <= CUTOFF)]
    e3["succ_30_90"] = has_successor(e3, pool, -30, 90)
    e3["succ_0_90"] = has_successor(e3, pool, 0, 90)
    e3["has_key"] = e3["address_key"].notna()
    rows = []
    for label, sub3 in (("All types", e3), ("Grocery (5 types)", e3[e3["is_grocery"]])):
        for name, flag in (("batch end", True), ("non-batch end", False)):
            s = sub3[(sub3["qa_batch_end"] == flag) & sub3["has_key"]]
            rows.append({
                "Types": label, "Ends": name, "Ends with address_key": len(s),
                "Successor -30..+90d": int(s["succ_30_90"].sum()), "Share -30..+90d": pct(s["succ_30_90"].sum(), len(s)),
                "Successor 0..+90d": int(s["succ_0_90"].sum()), "Share 0..+90d": pct(s["succ_0_90"].sum(), len(s)),
            })
    out += [
        "## 3. New record at the same address within the window",
        "",
        f"Scope: ends on or before {SUCCESSOR_CUTOFF.date()} (so the +90-day window closes by {DATA_THROUGH}); successor = a different",
        "Record ID of any store type at the same `address_key` (standardized number + street + ZIP5) authorized in the window.",
        f"Ends without an address_key are excluded ({int((~e3['has_key']).sum()):,} of {len(e3):,} ends in scope). "
        "-30..+90 is the approved ownership-change window; 0..+90 is shown for comparison.",
        "",
        md_table(pd.DataFrame(rows)),
        "",
    ]

    # (4) concentration by year
    ends["year"] = ends["end_date"].dt.year
    yr = ends.groupby("year").agg(ended=("period_id", "size"), batch=("qa_batch_end", "sum")).reset_index()
    batch_days = ends[ends["qa_batch_end"]].groupby("year")["end_date"].nunique()
    yr["batch_dates"] = yr["year"].map(batch_days).fillna(0).astype(int)
    yr["batch_share_of_year"] = [pct(x, y) for x, y in zip(yr["batch"], yr["ended"])]
    yr["share_of_all_batch_ends"] = [pct(x, yr["batch"].sum()) for x in yr["batch"]]
    grocery_y = ends[ends["is_grocery"]].groupby("year").agg(g_ended=("period_id", "size"), g_batch=("qa_batch_end", "sum"))
    yr = yr.merge(grocery_y, left_on="year", right_index=True, how="left").fillna(0)
    yr["grocery_batch_share"] = [pct(x, y) for x, y in zip(yr["g_batch"], yr["g_ended"])]
    yr = yr.rename(columns={"g_ended": "grocery_ended", "g_batch": "grocery_batch"})
    yr[["batch", "grocery_ended", "grocery_batch"]] = yr[["batch", "grocery_ended", "grocery_batch"]].astype(int)
    out += ["## 4. Concentration by year", "", md_table(yr), ""]

    # (5) re-authorization under the SAME Record ID after the end. Only re-authorizations that
    #     started by DATA_THROUGH are visible, so recent ends are right-censored; the second
    #     scope (ends through 2020) gives every end at least a year of follow-up.
    d = d.sort_values(["record_id", "period_seq"])
    nxt = d.assign(next_auth=d.groupby("record_id")["auth_date"].shift(-1)).set_index("period_id")["next_auth"]
    ends["next_auth"] = ends["period_id"].map(nxt).where(lambda s: s <= CUTOFF)
    ends["gap_days"] = (ends["next_auth"] - ends["end_date"]).dt.days
    rows5 = []
    for scope_label, scope_end in (("ends through 2021-12-31", CUTOFF), ("ends through 2020-12-31", pd.Timestamp("2020-12-31"))):
        s = ends[ends["end_date"] <= scope_end]
        for tname, g in (("All types", s), ("Grocery (5 types)", s[s["is_grocery"]])):
            for ename, flag in (("batch end", True), ("non-batch end", False)):
                # one row per Record ID: its first end of that kind in scope
                x = g[g["qa_batch_end"] == flag].sort_values("end_date").drop_duplicates("record_id")
                late = x["gap_days"] > 90
                bridged = x["gap_days"] <= 90
                none = x["gap_days"].isna()
                rows5.append({
                    "Scope": scope_label, "Types": tname, "Ends": ename, "Record IDs": len(x),
                    "Re-authorized, same ID, >90d later": int(late.sum()), "Share >90d": pct(late.sum(), len(x)),
                    "Next period <=90d (bridged/overlap)": int(bridged.sum()), "Share <=90d": pct(bridged.sum(), len(x)),
                    "No later period seen": int(none.sum()), "Share none": pct(none.sum(), len(x)),
                    "Median gap of >90d (days)": int(x.loc[late, "gap_days"].median()) if late.any() else "n/a",
                })
    out += [
        "## 5. Same-Record-ID re-authorization after the end",
        "",
        "Unit: Record IDs, using each Record ID's first end of the given kind (batch / non-batch) in scope. A re-authorization is the",
        f"same Record ID's next authorization period, visible only if it started by {DATA_THROUGH}. The 2021-scope rows are therefore",
        "right-censored for late-2021 ends; the 2020-scope rows give every end at least a year of follow-up.",
        "",
        md_table(pd.DataFrame(rows5)),
        "",
    ]

    # Hand-check sample: 20 random grocery batch-end stores in cohort-relevant years (2008-2021).
    # Written once; never overwritten, because verified_status is filled in by hand.
    hc_path = DOCS / "batch_end_handcheck.csv"
    pool_hc = ends[ends["qa_batch_end"] & ends["is_grocery"] & (ends["end_date"] >= pd.Timestamp("2008-01-01"))]
    out += [
        "## Hand-check sample",
        "",
        f"`docs/batch_end_handcheck.csv`: 20 random grocery batch-end stores from {len(pool_hc):,} eligible (end dates 2008-01-01 to 2021-12-31,",
        "seed 20261102). Fill in `verified_status` by hand (e.g. closed / still open / ownership change / unclear). The script will not overwrite an existing file.",
        "",
    ]
    if hc_path.exists():
        print(f"{hc_path} exists; not overwriting")
    else:
        hc = pool_hc.sample(n=20, random_state=20261102).sort_values("end_date")
        hc = pd.DataFrame({
            "record_id": hc["record_id"], "store_name": hc["store_name"], "store_type": hc["store_type"],
            "address": (hc["street_number"].fillna("") + " " + hc["street_name"]).str.strip(),
            "city": hc["city"], "zip5": hc["zip5"], "county": hc["county"],
            "end_date": hc["end_date"].dt.strftime("%Y-%m-%d"), "verified_status": "",
        })
        hc.to_csv(hc_path, index=False, encoding="utf-8-sig")
        print(f"Wrote {hc_path}")

    (DOCS / "batch_end_profile.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {DOCS / 'batch_end_profile.md'}")


if __name__ == "__main__":
    main()
