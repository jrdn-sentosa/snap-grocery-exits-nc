"""Label rates by year, TRAIN and VALIDATION years only (2008-2021).

Reads : data/interim/spells.parquet, data/interim/periods_spells.parquet
Writes: docs/label_rates_by_year.md

Test-set discipline: the store-years are built only for years <= 2021, so no 2022-2024 row is
ever constructed here. (Labels for 2021 use successor starts up to 90 days into 2022, which is
how the ownership-change rule is defined; no 2022+ store-year is touched.)
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "prep"))
from common import DOCS, INTERIM, TRAIN_END_YEAR, VAL_END_YEAR, ensure_dirs  # noqa: E402
from store_years import build_store_years  # noqa: E402

YEARS = range(2008, VAL_END_YEAR + 1)


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def summarize(g: pd.DataFrame) -> dict:
    n, ex = len(g), int(g["exit_12m"].sum())
    strict = g["exit_12m_strict"].dropna()
    batch_ex = int(g["exit_is_batch"].fillna(False).astype(bool).sum())
    return {
        "store_years": f"{n:,}",
        "exits": ex,
        "exit_12m rate": f"{100 * ex / n:.1f}%",
        "of which batch": batch_ex,
        "batch share of exits": f"{100 * batch_ex / ex:.1f}%" if ex else "n/a",
        "ownership-change ends": int(g["qa_ownership_change_in_year"].sum()),
        "strict n": f"{len(strict):,}",
        "strict exits": int(strict.sum()),
        "exit_12m_strict rate": f"{100 * strict.sum() / len(strict):.1f}%",
    }


def main() -> None:
    ensure_dirs()
    spells = pd.read_parquet(INTERIM / "spells.parquet")
    periods = pd.read_parquet(INTERIM / "periods_spells.parquet")
    sy = build_store_years(spells, periods, YEARS)
    assert sy["year"].max() <= VAL_END_YEAR

    sy["split"] = sy["year"].map(lambda y: "train" if y <= TRAIN_END_YEAR else "validation")
    rows = [{"year": y, "split": s, **summarize(g)} for (y, s), g in sy.groupby(["year", "split"])]
    rows += [
        {"year": f"2008-{TRAIN_END_YEAR}", "split": "train (total)", **summarize(sy[sy["split"] == "train"])},
        {"year": f"{TRAIN_END_YEAR + 1}-{VAL_END_YEAR}", "split": "validation (total)", **summarize(sy[sy["split"] == "validation"])},
    ]
    by_type = [{"store_type": t, **summarize(g)} for t, g in sy[sy["split"] == "train"].groupby("store_type")]

    out = [
        "# Label rates by year (train and validation years only)",
        "",
        "Generated by `src/eda/label_rates.py`; do not edit by hand. Store-years are grocery-type Record IDs active on",
        "Jan 1 of year t; years 2008-2021 only (2022-2024 is the reserved test set and is never built here).",
        "",
        "- `exit_12m` (primary): a true exit (not an ownership change) ends in year t, batch ends included.",
        "- `exit_12m_strict`: same, but rows whose exit is a `qa_batch_end` are EXCLUDED (label missing), so `strict n` is smaller.",
        "- `ownership-change ends`: store-years whose spell ended in t as an ownership change (label 0 in both).",
        "",
        md_table(pd.DataFrame(rows)),
        "",
        "## Train-period rate by store type (2008-2018)",
        "",
        md_table(pd.DataFrame(by_type)),
        "",
    ]
    (DOCS / "label_rates_by_year.md").write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {DOCS / 'label_rates_by_year.md'}")


if __name__ == "__main__":
    main()
