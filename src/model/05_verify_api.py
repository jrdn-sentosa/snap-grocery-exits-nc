"""D4: check that the deployed API returns the same probabilities as the saved Pipeline run locally.

    uv run python src/model/05_verify_api.py                      # deployed URL below
    uv run python src/model/05_verify_api.py --url http://127.0.0.1:8000   # a local `fastapi dev` server

Takes 20 validation store-years (cohorts 2019-2021; seed 2026): 17 at random plus 3 with at least one missing
feature value, so the API's null handling is exercised too. Scores them with models/exit_model.joblib locally,
POSTs the same raw records to /predict, and asserts every probability matches to within 1e-9. Also compares the
deployed model file's SHA-256 (from /model-info) with the local one.

Writes docs/api_verification.md. Only predicted probabilities are written, no outcomes; the test file is never read.
"""

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import requests

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))  # joblib.load imports src.model.transformers
from common_model import DOCS, SEED, TRAINVAL, VAL_YEARS  # noqa: E402

DEFAULT_URL = "https://hgmccall--snap-grocery-exits-api.us-east.modal.run"
MODEL_PATH = ROOT / "models" / "exit_model.joblib"
META = json.loads(MODEL_PATH.with_suffix(".json").read_text(encoding="utf-8"))
FEATURES = META["features"]
TOL = 1e-9
N_RANDOM, N_MISSING = 17, 3


def sample_rows() -> pd.DataFrame:
    df = pd.read_parquet(TRAINVAL)
    assert df["year"].max() <= 2021, "test-period rows found in the train/validation file"
    val = df[df["year"].isin(VAL_YEARS)].copy()
    val["cohort_year"] = val["year"].astype(int)
    has_missing = val[FEATURES].isna().any(axis=1)
    miss = val[has_missing].sample(N_MISSING, random_state=SEED)
    rand = val.drop(miss.index).sample(N_RANDOM, random_state=SEED)
    return pd.concat([rand, miss])


def to_record(row: pd.Series) -> dict:
    """Raw feature values as JSON: missing -> null, numpy/pandas scalars -> Python."""
    rec = {"record_id": str(row["record_id"]), "cohort_year": int(row["cohort_year"])}
    for c in FEATURES:
        v = row[c]
        rec[c] = None if pd.isna(v) else (v.item() if hasattr(v, "item") else v)
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default=DEFAULT_URL)
    args = ap.parse_args()
    url = args.url.rstrip("/")

    rows = sample_rows()
    model = joblib.load(MODEL_PATH)
    local = model.predict_proba(rows[[*FEATURES, "cohort_year"]])[:, 1]

    info = requests.get(f"{url}/model-info", timeout=120).json()  # first call may wake a cold container
    resp = requests.post(f"{url}/predict", json={"records": [to_record(r) for _, r in rows.iterrows()]}, timeout=120)
    resp.raise_for_status()
    preds = resp.json()["predictions"]
    assert [p["record_id"] for p in preds] == rows["record_id"].astype(str).tolist(), "API returned rows out of order"
    remote = np.array([p["exit_probability"] for p in preds])
    diff = np.abs(remote - local)
    local_sha = hashlib.sha256(MODEL_PATH.read_bytes()).hexdigest()
    ok = bool(diff.max() <= TOL) and info["joblib_sha256"] == local_sha

    missing_cols = rows[FEATURES].isna().apply(lambda r: ", ".join(c for c in FEATURES if r[c]), axis=1)
    rt = info["runtime_versions"]
    L = ["# API verification: local Pipeline vs deployed Modal API", "",
         "Generated by `src/model/05_verify_api.py`; do not edit by hand.", "",
         f"- Checked: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC",
         f"- Deployed API: {url} (`POST /predict`, docs at {url}/docs)",
         f"- Rows: {len(rows)} validation store-years (cohorts 2019-2021, seed {SEED}): {N_RANDOM} random and "
         f"{N_MISSING} with a missing feature value (sent as JSON `null`). Only predictions are shown; no outcomes.",
         f"- Model file SHA-256: local `{local_sha[:16]}...`, deployed `{info['joblib_sha256'][:16]}...` "
         f"({'same' if info['joblib_sha256'] == local_sha else 'DIFFERENT'})",
         f"- Versions: local Python {sys.version.split()[0]}, scikit-learn {META['versions']['scikit-learn']}, "
         f"pandas {pd.__version__}, numpy {np.__version__}; deployed Python {rt['python']}, scikit-learn "
         f"{rt['scikit-learn']}, pandas {rt['pandas']}, numpy {rt['numpy']}",
         f"- **Result: {'PASS' if ok else 'FAIL'}.** Largest absolute difference {diff.max():.3g} "
         f"(tolerance {TOL:g}); {int((diff == 0).sum())} of {len(rows)} probabilities are bit-for-bit identical.", "",
         "| record_id | cohort | store_type | missing features | local probability | API probability | abs diff |",
         "|---|---|---|---|---|---|---|"]
    for (_, r), lp, rp, d, mc in zip(rows.iterrows(), local, remote, diff, missing_cols):
        L.append(f"| {r['record_id']} | {r['cohort_year']} | {r['store_type']} | {mc} | {lp:.15f} | {rp:.15f} | {d:.1e} |")
    out = DOCS / "api_verification.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[5:11]))
    print(f"Wrote {out.relative_to(ROOT)}")
    assert ok, "deployed API does not match the local Pipeline"


if __name__ == "__main__":
    main()
